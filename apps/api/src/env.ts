import type { KnowledgeIndexerCore } from "./knowledge/indexer.ts";
import type { OfficePresenceCore } from "./office/presence.ts";
import type { ActorDirectory, BlobPort, InferencePort, KeyValuePort, SqlPort, VectorIndexPort } from "./platform/ports.ts";
import type { AgentRuntimePort } from "./runtime/port.ts";
import type { WorkstationPort } from "./workstation/port.ts";

/** Async view of an actor: on Cloudflare every call to a Durable Object is a remote call. */
type Remote<T> = { [K in keyof T]: T[K] extends (...args: infer A) => infer R ? (...args: A) => Promise<Awaited<R>> : never };

/** The live hub: browsers connect over WebSocket with a one-time ticket; the core broadcasts events. */
export interface LiveHubPort {
  fetch(request: Request): Promise<Response>;
  issueTicket(): Promise<string>;
  broadcast(message: string): Promise<number>;
}

export type OfficePresencePort = Remote<Pick<OfficePresenceCore, "configure" | "setViewers" | "recordEvent">>;
export type KnowledgeIndexerPort = Remote<Pick<KnowledgeIndexerCore, "start" | "status">>;

/**
 * Everything the agent core gets from its host (ADR 0040): ports for data, actors and models, plus configuration
 * and secrets. Cloudflare builds it from its bindings in cloudflare/platform.ts; the core never sees a binding type.
 */
export interface Env {
  DB: SqlPort;
  CONFIG: KeyValuePort;
  FILES: BlobPort;
  AI: InferencePort;
  AGENTS: ActorDirectory<AgentRuntimePort>;
  HUB: ActorDirectory<LiveHubPort>;
  OFFICE: ActorDirectory<OfficePresencePort>;
  /** Knowledge index of the projects (plan stage 3): vectors from @cf/baai/bge-m3, 1024 dimensions, cosine. */
  KNOWLEDGE: VectorIndexPort;
  INDEXER: ActorDirectory<KnowledgeIndexerPort>;
  /** Isolated execution of the agents (ADR 0036). Absent until a host provides it (Cloudflare: Workers Paid). */
  WORKSTATION?: ActorDirectory<WorkstationPort>;

  DEFAULT_REPO: string;
  /** GitHub accounts whose repositories may become projects, comma-separated. Organizations stay out until decided. */
  GITHUB_OWNERS: string;
  CF_ACCOUNT_ID: string;
  AI_GATEWAY_ID: string;
  MODEL_VIA_GATEWAY: string;
  /** "production" (branch main) or "dev" (branch dev). */
  API_ENV: string;
  /** Names of the storage behind the bindings; shown in the portal, never used to connect. */
  STORAGE: { d1: string; d1Region: string; kv: string; r2: string };
  /** "true" once the models in apps/api/modal/llm.py are deployed; until then Modal stays unselectable. */
  MODAL_ENABLED?: string;
  /** workers.dev subdomain of the account; preview URLs are built from it (ADR 0036). */
  CF_WORKERS_SUBDOMAIN?: string;

  /** Shared with the portal server, one value per environment; the browser never sees it. */
  API_SERVICE_TOKEN?: string;
  GEMINI_API_KEY?: string;
  /** Fine-grained GitHub token: contents, pull requests and checks on the managed repositories. */
  AGENT_GITHUB_TOKEN?: string;
  /** GitHub App (ADR 0031): id and private key (PEM). Where the app is installed it replaces the token. */
  AGENT_GH_APP_ID?: string;
  AGENT_GH_APP_PRIVATE_KEY?: string;
  /** Secret of the app's webhook; deliveries without a matching signature are refused. */
  AGENT_GH_WEBHOOK_SECRET?: string;
  OPENROUTER_API_KEY?: string;
  /**
   * Encrypts the model provider keys tenants enter in the portal (ADR 0033). Generated by `pnpm ugur api secrets`,
   * kept in Infisical (prod). Losing it makes stored keys unreadable; they then have to be entered again.
   */
  PROVIDER_KEYS_SECRET?: string;
  /** Key of the vLLM servers on Modal (apps/api/modal/llm.py); same value as the Modal secret uguroezdamar-llm. */
  MODAL_LLM_API_KEY?: string;
  /** Cloudflare token for preview uploads (Workers Scripts: Edit). Stays in the Worker; the container never sees it. */
  AGENT_CF_PREVIEW_TOKEN?: string;
}

/** Reads a secret by the name a model provider is configured with. */
export function secret(env: Env, name: string): string | undefined {
  const value = (env as unknown as Record<string, unknown>)[name];
  return typeof value === "string" && value.length > 0 ? value : undefined;
}
