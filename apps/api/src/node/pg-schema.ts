import { readFileSync } from "node:fs";
import { join } from "node:path";
import { DatabaseSync } from "node:sqlite";
import { toPostgres } from "../postgres/dialect.ts";
import { applyMigrations } from "./sql.ts";

/**
 * The Postgres schema of the API (ADR 0045, R2), derived from the SQLite end state of apps/api/migrations: the same
 * tables, columns, defaults, checks, keys, indexes and seed rows. As long as D1 is the production database, the
 * SQLite migrations stay the source; `pnpm --filter @ugur/node-host pg:schema` regenerates the baseline and a test
 * fails when it is stale. Once Postgres holds data (R5), it gets incremental migrations of its own.
 */

/** Tables whose code orders by SQLite's implicit rowid; Postgres gets an identity column of that name. */
const ROWID_TABLES = new Set(["tasks", "workflow_steps"]);

const FTS_INDEX = "CREATE INDEX knowledge_fts_search ON knowledge_fts USING GIN (to_tsvector('simple', coalesce(heading, '') || ' ' || coalesce(text, '')));";

function quoteValue(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number" || typeof value === "bigint") return String(value);
  if (value instanceof Uint8Array) return `'\\x${Buffer.from(value).toString("hex")}'::bytea`;
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** One CREATE TABLE of SQLite as Postgres DDL. */
export function tableDdl(sql: string, table: string): { ddl: string; identity: string | null } {
  let identity: string | null = null;
  let ddl = sql
    // Line comments of the migrations stay there; they may hold a semicolon.
    .replace(/--[^\n]*/g, "")
    .replace(/^CREATE TABLE (IF NOT EXISTS )?/i, "CREATE TABLE ")
    .replace(/\b(\w+)\s+INTEGER\s+PRIMARY\s+KEY(\s+AUTOINCREMENT)?/i, (_match, column: string) => {
      identity = column;
      return `${column} BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`;
    })
    .replace(/\bINTEGER\b/gi, "BIGINT")
    .replace(/\bREAL\b/gi, "DOUBLE PRECISION")
    .replace(/\bBLOB\b/gi, "BYTEA");
  // Defaults and checks may use SQLite functions; the statement translator knows them.
  ddl = toPostgres(ddl).text;
  if (ROWID_TABLES.has(table)) ddl = ddl.replace(/\)\s*$/, ",\n  rowid BIGINT GENERATED ALWAYS AS IDENTITY\n)");
  return { ddl: `${ddl};`, identity };
}

/** Orders tables so that every referenced table comes first (self references aside). */
function byDependency(tables: { name: string; sql: string }[]): { name: string; sql: string }[] {
  const names = new Set(tables.map((table) => table.name));
  const done = new Set<string>();
  const ordered: { name: string; sql: string }[] = [];
  const visit = (table: { name: string; sql: string }, path: Set<string>) => {
    if (done.has(table.name) || path.has(table.name)) return;
    path.add(table.name);
    for (const [, target] of table.sql.matchAll(/REFERENCES\s+(\w+)/gi)) {
      const dependency = tables.find((candidate) => candidate.name === target);
      if (dependency && target !== table.name && names.has(target ?? "")) visit(dependency, path);
    }
    done.add(table.name);
    ordered.push(table);
  };
  for (const table of tables) visit(table, new Set());
  return ordered;
}

export function postgresBaseline(migrationsDir: string, migrationFiles?: string[]): string {
  const db = new DatabaseSync(":memory:");
  if (migrationFiles) {
    for (const file of migrationFiles) db.exec(readFileSync(join(migrationsDir, file), "utf8"));
  } else applyMigrations(db, migrationsDir);
  const objects = db.prepare("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' AND name NOT LIKE '_migrations' AND name NOT LIKE 'knowledge_fts_%' ORDER BY name").all() as { type: string; name: string; tbl_name: string; sql: string }[];
  const tables = byDependency(objects.filter((object) => object.type === "table").map((object) => ({ name: object.name, sql: object.sql })));

  const out: string[] = [
    "-- Generated from apps/api/migrations (SQLite end state) by apps/api/src/node/pg-schema.ts; do not edit.",
    "-- Regenerate: pnpm --filter @ugur/node-host pg:schema (ADR 0045, R2).",
    "",
  ];
  const identities: { table: string; column: string }[] = [];
  for (const table of tables) {
    if (/^CREATE VIRTUAL TABLE/i.test(table.sql)) {
      // FTS5 has no Postgres twin; a plain table with a text-search index serves the same queries (dialect.ts).
      out.push(`CREATE TABLE ${table.name} (\n  chunk_id TEXT,\n  tenant_id TEXT,\n  project_id TEXT,\n  heading TEXT,\n  text TEXT\n);`, FTS_INDEX, "");
      continue;
    }
    const { ddl, identity } = tableDdl(table.sql, table.name);
    if (identity) identities.push({ table: table.name, column: identity });
    out.push(ddl, "");
  }
  for (const index of objects.filter((object) => object.type === "index")) {
    out.push(`${toPostgres(index.sql.replace(/^CREATE (UNIQUE )?INDEX IF NOT EXISTS/i, "CREATE $1INDEX")).text};`);
  }
  out.push("");

  // Seed rows the migrations inserted (catalog, agents, defaults).
  for (const table of tables) {
    if (/^CREATE VIRTUAL TABLE/i.test(table.sql)) continue;
    const rows = db.prepare(`SELECT * FROM "${table.name}"`).all() as Record<string, unknown>[];
    // Timestamps the migrations took from the clock are left to Postgres' default, so the file is reproducible.
    const clocked = new Set(
      (db.prepare(`SELECT name, dflt_value FROM pragma_table_info('${table.name}')`).all() as { name: string; dflt_value: string | null }[])
        .filter((column) => /unixepoch/i.test(column.dflt_value ?? ""))
        .map((column) => column.name),
    );
    for (const row of rows) {
      const columns = Object.keys(row).filter((column) => !clocked.has(column));
      out.push(`INSERT INTO ${table.name} (${columns.join(", ")}) OVERRIDING SYSTEM VALUE VALUES (${columns.map((column) => quoteValue(row[column])).join(", ")});`);
    }
  }
  for (const { table, column } of identities) {
    out.push(`SELECT setval(pg_get_serial_sequence('${table}', '${column}'), COALESCE((SELECT MAX(${column}) FROM ${table}), 0) + 1, false);`);
  }
  db.close();
  // Checkouts on Windows bring CRLF into the stored CREATE statements; the file is the same on every system.
  return `${out.join("\n").replace(/\r\n?/g, "\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;
}
